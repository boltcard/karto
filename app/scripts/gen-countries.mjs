// Writes src/onboarding/countryData.ts: every ISO 3166-1 country as
// [alpha-2, alpha-3, English name], sorted by name, from i18n-iso-countries
// (MIT). The country picker defaults from the phone's region (alpha-2) and
// LNVPS wants alpha-3. Run: node scripts/gen-countries.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkg = dirname(require.resolve('i18n-iso-countries/package.json'));
const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
const codes = JSON.parse(readFileSync(join(pkg, 'codes.json'), 'utf8'));
const names = JSON.parse(readFileSync(join(pkg, 'langs', 'en.json'), 'utf8')).countries;

const rows = codes
  .map(([alpha2, alpha3]) => {
    const n = names[alpha2];
    return [alpha2, alpha3, Array.isArray(n) ? n[0] : n];
  })
  .sort((a, b) => a[2].localeCompare(b[2], 'en'));

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'onboarding', 'countryData.ts');
writeFileSync(out, `// Generated by scripts/gen-countries.mjs from i18n-iso-countries ${version}
// (MIT, https://github.com/michaelwittig/node-i18n-iso-countries). Do not edit.
// [alpha-2, alpha-3, English name], sorted by name.
export const COUNTRY_ROWS: readonly (readonly [string, string, string])[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`);
console.log(`${rows.length} countries -> ${out}`);
